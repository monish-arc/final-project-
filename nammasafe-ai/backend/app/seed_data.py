def get_processed_seed_data() -> Dict[str, Any]:
    """Processes raw records through mathematical risk formulas and returns fully linked data."""
    
    # 1. Process Habitations
    habitations = []
    for raw in RAW_HABITATIONS:
        h_score = calculate_hazard_score(
            landslide_risk=raw["landslide_risk"],
            flood_risk=raw["flood_risk"],
            extreme_rainfall_risk=raw["extreme_rainfall_risk"],
            past_disaster_frequency=raw["past_disaster_frequency"],
        )
        v_score = calculate_vulnerability_score(
            population=raw["population"],
            households=raw["households"],
            children_count=raw["children_count"],
            elderly_count=raw["elderly_count"],
            hospital_distance_km=raw["hospital_distance_km"],
            road_access_score=raw["road_access_score"],
        )
        disaster_hist_score = min(100.0, raw["disaster_history_count"] * 16.0)
        p_score, p_level = calculate_relocation_priority(
            hazard_score=h_score,
            vulnerability_score=v_score,
            disaster_history_score=disaster_hist_score,
        )
        
        hab = {
            **raw,
            "hazard_score": h_score,
            "vulnerability_score": v_score,
            "priority_score": p_score,
            "priority_level": p_level,
            "location_geojson": {
                "type": "Point",
                "coordinates": [raw["longitude"], raw["latitude"]],
            },
        }
        habitations.append(hab)

    # 2. Process Relocation Sites
    relocation_sites = []
    for raw in RAW_RELOCATION_SITES:
        suitability = calculate_site_suitability(
            low_hazard_score=raw["low_hazard_score"],
            flat_land_score=raw["flat_land_score"],
            road_score=raw["road_score"],
            water_score=raw["water_score"],
            school_score=raw["school_score"],
            hospital_score=raw["hospital_score"],
        )
        final_cap = calculate_carrying_capacity(
            land_capacity=raw["land_capacity_families"],
            water_capacity=raw["water_capacity_families"],
            school_capacity=raw["school_capacity_families"],
            health_capacity=raw["health_capacity_families"],
            road_capacity=raw["road_capacity_families"],
        )
        avail_cap = max(0, final_cap - raw["current_occupancy_families"])
        
        site = {
            **raw,
            "suitability_score": suitability,
            "final_capacity_families": final_cap,
            "available_capacity_families": avail_cap,
            "location_geojson": {
                "type": "Point",
                "coordinates": [raw["longitude"], raw["latitude"]],
            },
        }
        relocation_sites.append(site)

    # 3. Generate Relocation Recommendations
    # Match high-priority habitations to most suitable safe sites
    recommendations = []
    sorted_habs = sorted(habitations, key=lambda x: x["priority_score"], reverse=True)
    
    # Preferred mapping for pilot
    site_map = {
        "hab-joshimath": ("site-gauchar-01", 350, "Approved"),
        "hab-raini": ("site-nandprayag-04", 120, "Approved"),
        "hab-tapovan": ("site-karanprayag-03", 180, "Under Review"),
        "hab-helang": ("site-karanprayag-03", 140, "Under Review"),
        "hab-ghat": ("site-gwaldam-02", 150, "Draft"),
        "hab-pandukeshwar": ("site-gauchar-01", 160, "Draft"),
        "hab-tharali": ("site-gwaldam-02", 110, "Draft"),
        "hab-urgam": ("site-nandprayag-04", 90, "Draft"),
        "hab-pipalkoti": ("site-gauchar-01", 100, "Draft"),
        "hab-mana": ("site-karanprayag-03", 60, "Draft"),
    }

    sites_by_id = {s["id"]: s for s in relocation_sites}
    for idx, h in enumerate(sorted_habs):
        pref_site_id, fams, status = site_map.get(h["id"], ("site-gauchar-01", 100, "Draft"))
        target_s = sites_by_id.get(pref_site_id, relocation_sites[0])
        
        # Risk reduction calculation
        residual_risk = max(5.0, (100.0 - target_s["suitability_score"]) * 0.4)
        risk_red = round(max(60.0, min(95.0, ((h["priority_score"] - residual_risk) / h["priority_score"]) * 100.0)), 1)
        
        rec = {
            "id": f"rec-{idx+1:03d}",
            "habitation_id": h["id"],
            "habitation_name": h["village_name"],
            "relocation_site_id": target_s["id"],
            "relocation_site_name": target_s["site_name"],
            "hazard_score": h["hazard_score"],
            "vulnerability_score": h["vulnerability_score"],
            "disaster_history_score": min(100.0, h["disaster_history_count"] * 16.0),
            "final_priority_score": h["priority_score"],
            "priority_level": h["priority_level"],
            "recommended_families": fams,
            "risk_reduction_percent": risk_red,
            "explanation": (
                f"Multi-hazard assessment in {h['village_name']} indicated composite risk score {h['priority_score']} "
                f"({h['priority_level']}). Shifting {fams} vulnerable households to {target_s['site_name']} "
                f"(Suitability index: {target_s['suitability_score']}/100) lowers hazard exposure by {risk_red}%. "
                f"Site verified for adequate water, access road, and public health service buffers."
            ),
            "status": status,
            "created_at": "2025-08-20T09:00:00Z",
        }
        recommendations.append(rec)

    return {
        "users": DEMO_USERS,
        "administrative_areas": ADMINISTRATIVE_AREAS,
        "risk_alerts": [],
        "user_sessions": [],
        "audit_events": [],
        "habitations": habitations,
        "relocation_sites": relocation_sites,
        "red_zones": RAW_RED_ZONES,
        "hazard_events": RAW_DISASTER_EVENTS,
        "recommendations": recommendations,
        "field_reports": RAW_FIELD_REPORTS,
        "infrastructure": INFRASTRUCTURE_DATA,
    }
